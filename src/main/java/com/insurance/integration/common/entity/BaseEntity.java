package com.insurance.integration.common.entity;

import jakarta.persistence.Column;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import lombok.Getter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;

import java.time.Instant;
import java.util.UUID;

/**
 * Abstract base entity providing common fields for all JPA entities.
 *
 * Provides UUID primary key (generated by the application via GenerationType.AUTO
 * which uses Hibernate's UUID generator), and audit timestamps populated by
 * Spring Data JPA auditing ({@link org.springframework.data.jpa.repository.config.EnableJpaAuditing}
 * in JpaConfig).
 *
 * All timestamp fields are stored as TIMESTAMPTZ (Instant) in UTC.
 */
@MappedSuperclass
@Getter
public abstract class BaseEntity {

    /**
     * UUID primary key.
     * GenerationType.AUTO with Hibernate 6 (Spring Boot 3.x) automatically uses
     * the UUID generator — no additional @GenericGenerator annotation needed.
     * Column is non-updatable since the PK must never change after creation.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(updatable = false, nullable = false)
    private UUID id;

    /**
     * Timestamp set when the entity is first persisted.
     * Populated by Spring Data JPA auditing via @CreatedDate,
     * with @CreationTimestamp as a fallback for Hibernate-managed persistence.
     */
    @CreatedDate
    @CreationTimestamp
    @Column(name = "created_at", updatable = false, nullable = false)
    private Instant createdAt;

    /**
     * Timestamp updated whenever the entity is modified.
     * Populated by Spring Data JPA auditing via @LastModifiedDate,
     * with @UpdateTimestamp as a fallback.
     */
    @LastModifiedDate
    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;
}
